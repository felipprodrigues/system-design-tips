/* Usage: node scripts/read-time.mjs [--check]. Run by predev and prebuild; the
   output is committed so a plain `next build` still has it.

   A proxy, not a transcript. Prose in a .tsx body is JSX text plus the string
   literals its data arrays render from, so markup — imports, class names, inline
   styles, SVG geometry — is dropped before counting. */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pages } from "../src/lib/content.ts";

const WORDS_PER_MINUTE = 200;
const BODIES = "src/concepts";
const OUT = "src/lib/readTime.ts";

function prose(source) {
  const stripped = source
    .replace(/^import[\s\S]*?from\s+["'][^"']+["'];?$/gm, "")
    .replace(/\bclassName=(?:"[^"]*"|\{[^}]*\})/g, "")
    .replace(/\bstyle=\{\{[\s\S]*?\}\}/g, "")
    .replace(/\b(?:d|viewBox|transform|fill|stroke|points)=["'][^"']*["']/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");

  const literals = [
    ...stripped.matchAll(/"([^"\\]*(?:\\.[^"\\]*)*)"|'([^'\\]*(?:\\.[^'\\]*)*)'/g),
  ].map((m) => m[1] ?? m[2] ?? "");
  const jsxText = [...stripped.matchAll(/>([^<>{}]+)</g)].map((m) => m[1]);

  return [...literals, ...jsxText].join(" ");
}

/* The Q&A is authored HTML rather than a component, so its words are in text
   nodes and nowhere else. */
function proseFromHtml(source) {
  return source
    .replace(/<(script|style)[\s\S]*?<\/\1>/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&[a-z]+;|&#x?[0-9a-f]+;/gi, " ");
}

function minutes(text) {
  const words = text.split(/[\s\u00a0]+/).filter((word) => /[a-zA-Z]{2}/.test(word)).length;
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE));
}

const read = (path) => {
  const source = readFileSync(path, "utf8");
  return path.endsWith(".html") ? proseFromHtml(source) : prose(source);
};

const concepts = readdirSync(BODIES)
  .filter((file) => file.endsWith(".tsx"))
  .sort()
  .map((file) => [file.replace(/\.tsx$/, ""), minutes(read(join(BODIES, file)))]);

const extras = pages.map((page) => [
  page.slug,
  minutes(page.sources.map(read).join(" ")),
]);

const entries = [...concepts, ...extras];

const generated =
  `// Generated by scripts/read-time.mjs — do not edit. Run \`npm run read-time\`.\n` +
  `export const readTime: Record<string, number> = {\n` +
  entries.map(([slug, mins]) => `  "${slug}": ${mins},\n`).join("") +
  `};\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== generated) {
    console.error(`${OUT} is stale — run \`npm run read-time\` and commit it.`);
    process.exit(1);
  }
  console.log(`read-time: ${concepts.length} concepts + ${extras.length} pages, up to date`);
} else {
  writeFileSync(OUT, generated);
  const total = entries.reduce((sum, [, mins]) => sum + mins, 0);
  console.log(`read-time: ${concepts.length} concepts + ${extras.length} pages, ${total} min total → ${OUT}`);
}
